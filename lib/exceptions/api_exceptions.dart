/// Base exception for all FRS API and Biometric errors.
abstract class FrsApiException implements Exception {
  final String message;
  const FrsApiException(this.message);

  @override
  String toString() => message;
}

/// HTTP 401: Probe facial embedding does not match claimed employee's reference template.
class BiometricMismatchException extends FrsApiException {
  final double similarityScore;
  final double requiredThreshold;

  BiometricMismatchException({
    required this.similarityScore,
    required this.requiredThreshold,
    String? message,
  }) : super(message ?? 'Biometric verification failed: identity mismatch.');

  String get scorePercentage => '${(similarityScore * 100).toStringAsFixed(1)}%';
  String get thresholdPercentage => '${(requiredThreshold * 100).toStringAsFixed(1)}%';
}

/// HTTP 401: 1:N probe facial embedding does not match any enrolled active employee.
class UnrecognizedFaceException extends FrsApiException {
  final double similarityScore;
  final double requiredThreshold;

  UnrecognizedFaceException({
    required this.similarityScore,
    required this.requiredThreshold,
    String? message,
  }) : super(message ?? 'Unrecognized face. No matching employee identified.');

  String get scorePercentage => '${(similarityScore * 100).toStringAsFixed(1)}%';
  String get thresholdPercentage => '${(requiredThreshold * 100).toStringAsFixed(1)}%';
}

/// HTTP 409: 1:N match found multiple candidate identities within the confidence margin.
class AmbiguousMatchException extends FrsApiException {
  final String firstCandidate;
  final double firstSimilarity;
  final String secondCandidate;
  final double secondSimilarity;
  final double margin;

  AmbiguousMatchException({
    required this.firstCandidate,
    required this.firstSimilarity,
    required this.secondCandidate,
    required this.secondSimilarity,
    required this.margin,
    String? message,
  }) : super(message ?? 'Ambiguous match: multiple candidate identities detected within confidence margin.');
}

/// HTTP 401: Missing or invalid API bearer token.
class AuthenticationException extends FrsApiException {
  const AuthenticationException(super.message);
}

/// HTTP 409: Duplicate punch attempt within the server cooldown window.
class CooldownException extends FrsApiException {
  final int remainingSeconds;
  final DateTime lastPunchTimeUtc;

  CooldownException({
    required this.remainingSeconds,
    required this.lastPunchTimeUtc,
    String? message,
  }) : super(message ?? 'Duplicate punch: cooldown active.');

  DateTime get lastPunchTimeLocal => lastPunchTimeUtc.toLocal();
}

/// HTTP 400: Biometric image quality rejection (e.g. motion blur, low sharpness).
class BiometricQualityException extends FrsApiException {
  const BiometricQualityException(super.message);
}

/// HTTP 422: YuNet face detector found 0 faces in frame.
class NoFaceDetectedException extends FrsApiException {
  const NoFaceDetectedException([String? message])
      : super(message ?? 'No face detected in camera capture. Please center your face.');
}

/// HTTP 422: YuNet face detector found >1 faces in frame.
class MultipleFacesDetectedException extends FrsApiException {
  const MultipleFacesDetectedException([String? message])
      : super(message ?? 'Multiple faces detected. Exactly 1 face must be in frame.');
}

/// HTTP 403: Employee profile exists but is marked inactive.
class InactiveEmployeeException extends FrsApiException {
  const InactiveEmployeeException(super.message);
}

/// HTTP 404: Employee ID not found in database.
class EmployeeNotFoundException extends FrsApiException {
  const EmployeeNotFoundException(super.message);
}

/// HTTP 404: Employee exists but has no active enrolled template.
class TemplateNotEnrolledException extends FrsApiException {
  const TemplateNotEnrolledException(super.message);
}

/// HTTP 400: Enrolled template was generated by an incompatible model version.
class IncompatibleModelVersionException extends FrsApiException {
  const IncompatibleModelVersionException(super.message);
}

/// HTTP 413: Upload size exceeded server maximum (5 MB).
class PayloadTooLargeException extends FrsApiException {
  const PayloadTooLargeException(super.message);
}

/// Network connectivity, socket, or timeout failure.
class NetworkException extends FrsApiException {
  const NetworkException(super.message);
}

/// HTTP 500: Internal server error.
class ServerException extends FrsApiException {
  const ServerException(super.message);
}
